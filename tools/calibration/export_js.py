#!/usr/bin/env python3
"""Export the Lightroom-matched models (the generated Swift data files of the Mac app) to a
JavaScript module for the LumaGrader web editor, so both apps use identical numbers.

Usage:
  python3 export_js.py <darkroom/Sources/Darkroom/Develop> <lumagrader/src/engine/lrModelData.js>
"""
import json
import re
import sys
from pathlib import Path


def numbers(text):
    return [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?(?:e-?\d+)?", text)]


def array(text, name):
    m = re.search(rf"static let {name}: \[Double\] = \[(.*?)\]", text, re.S)
    return numbers(m.group(1))


def slider_tables(text, names):
    out = {}
    for name in names:
        m = re.search(rf"\.{name}: (?:ToneModel\.)?SliderTable\(\s*amounts: \[(.*?)\],\s*offsets: \[(.*?)\]\s*\),", text, re.S)
        rows = [numbers(r) for r in re.findall(r"\[([^\[\]]+)\]", m.group(2))]
        out[name] = {"amounts": numbers(m.group(1)), "offsets": rows}
    return out


def main():
    src, target = Path(sys.argv[1]), Path(sys.argv[2])
    tone = (src / "ToneModelData.swift").read_text()
    local = (src / "LocalToneData.swift").read_text()
    color = (src / "ColorCalibrationData.swift").read_text()
    hsl = (src / "HSLModelData.swift").read_text()

    zone = re.search(r"zoneRange = \((-?[\d.]+), (-?[\d.]+)\)", local)
    matrices = {}
    for m in re.finditer(r"slider: \.(\w+), amount: (-?[\d.]+), d: \[(.*?)\]\),", color):
        rows = [numbers(r) for r in re.findall(r"\[([^\[\]]+)\]", m.group(3))]
        matrices.setdefault(m.group(1), []).append({"amount": float(m.group(2)), "d": rows})

    data = {
        "tone": {
            "exposureStops": array(tone, "exposureStops"),
            "exposureCurve": array(tone, "exposureCurve"),
            "sliders": slider_tables(tone, ["contrast", "whites", "blacks"]),
        },
        "local": {
            "zoneMix": float(re.search(r"zoneMix = ([\d.]+)", local).group(1)),
            "shadowsChroma": float(re.search(r"shadowsChroma = ([\d.]+)", local).group(1)),
            "highlightsChroma": float(re.search(r"highlightsChroma = ([\d.]+)", local).group(1)),
            "zoneRange": [float(zone.group(1)), float(zone.group(2))],
            "sliders": slider_tables(local, ["shadows", "highlights"]),
        },
        "matrices": matrices,
        "hsl": {
            "hueBins": int(re.search(r"hueBins = (\d+)", hsl).group(1)),
            "chromaEdges": numbers(re.search(r"chromaEdges: \[Double\] = \[(.*?)\]", hsl).group(1)),
            "encoded": re.search(r'encoded = "([^"]+)"', hsl).group(1),
        },
    }
    target.write_text(
        "// Generated by photo-studio tools/calibration/export_js.py from the Mac app's\n"
        "// Lightroom-matched tables (measured Oct 2026) — don't edit by hand.\n"
        f"export const LR_MODEL = {json.dumps(data, separators=(',', ':'))}\n")
    print(f"✓ Wrote {target} ({target.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
