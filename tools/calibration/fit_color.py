#!/usr/bin/env python3
"""Fit Calibration (red/green/blue primary hue + saturation) and global Saturation to Lightroom.

Usage:
  python3 fit_color.py <kit folder> <output .swift file>

Each of these behaves like a 3×3 colour matrix on linear RGB in Lightroom (measured, Oct
2026: ΔE ≈ 0.4–0.7 against the exports). The matrix keeps white white (rows sum to 1), so
it's fitted as I + D with D·(1,1,1) = 0, separately for the + and − side of each slider.
Writes ColorCalibrationData.swift.
"""
import re
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
import compare  # noqa: E402

PATTERN = re.compile(r"cal_\d\d_(red|green|blue)?(hue|saturation)_([mp])([\d.]+)")


def downsample(a, f=4):
    h, w = a.shape[:2]
    return a[:h // f * f, :w // f * f].reshape(h // f, f, w // f, f, -1).mean((1, 3))


def fit_d(x, y, mask):
    X = np.stack([x[mask, 0] - x[mask, 2], x[mask, 1] - x[mask, 2]], 1)
    d = np.zeros((3, 3))
    for r in range(3):
        (d1, d2), *_ = np.linalg.lstsq(X, y[mask, r] - x[mask, r], rcond=None)
        d[r] = [d1, d2, -d1 - d2]
    return d


def main():
    kit, target = Path(sys.argv[1]).expanduser(), Path(sys.argv[2]).expanduser()
    source = downsample(compare.load(kit / "source.tif"))
    x = compare.decode(source).reshape(-1, 3)
    usable = (source.reshape(-1, 3).max(1) < 0.97) & (source.reshape(-1, 3).min(1) > 0.02)
    entries = []
    for key, path in sorted(compare.index(kit / "adobe").items()):
        m = PATTERN.search(key)
        if not m:
            continue
        primary, part, sign, amount = m.groups()
        name = (primary + part.capitalize()) if primary else "saturation"
        amount = (-1 if sign == "m" else 1) * float(amount)
        out = downsample(compare.load(path))
        mask = usable & (out.reshape(-1, 3).max(1) < 0.97)
        d = fit_d(x, compare.decode(out).reshape(-1, 3), mask)
        pred = np.clip(x @ (np.eye(3) + d).T, 0, None).reshape(source.shape)
        pred = np.where(pred <= 0.0031308, pred * 12.92, 1.055 * np.power(pred, 1 / 2.4) - 0.055)
        err = np.linalg.norm(compare.oklab(np.clip(pred, 0, 1)) - compare.oklab(out), axis=-1).mean() * 100
        print(f"  {name} {amount:+g}: ΔE {err:.2f}")
        entries.append((name, amount, d))
    lines = [
        "// Generated by tools/calibration/fit_color.py from Lightroom exports — don't edit by hand.",
        "",
        "extension ColorCalibration {",
        "    /// Measured D (rows, linear sRGB) per slider and amount: matrix = I + D · value / amount.",
        "    static let measured: [Measured] = [",
    ]
    for name, amount, d in entries:
        rows = ", ".join("[" + ", ".join(f"{v:.6f}" for v in row) + "]" for row in d)
        lines.append(f'        Measured(slider: .{name}, amount: {amount:g}, d: [{rows}]),')
    lines += ["    ]", "}", ""]
    target.write_text("\n".join(lines))
    print(f"✓ Wrote {target}")


if __name__ == "__main__":
    main()
