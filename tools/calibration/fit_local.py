#!/usr/bin/env python3
"""Fit LumaGrader's Shadows and Highlights to Lightroom.

Usage:
  python3 fit_local.py <kit folder> <output .swift file>

Model (measured on Lightroom, Oct 2026):
  * Each pixel gets a gain in EV that depends on its zone value
        v = α · base + (1 − α) · log2(Y)      (EV, 0 = white; + Exposure)
    where `base` is the app's edge-aware local brightness (GuidedFilter, replicated here).
  * The gain per zone value is measured for every exported amount (median over the photo
    and chart) and interpolated between amounts.
  * Lightroom changes saturation less than a plain brightness gain would; modelled as a
    chroma factor 2^(−β · gain), β separate for Shadows and Highlights.
Writes LocalToneData.swift.
"""
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter1d, uniform_filter

sys.path.insert(0, str(Path(__file__).parent))
import compare  # noqa: E402

ALPHA = 0.75
BETA = {"shadows": 0.09, "highlights": 0.35}
V_MIN, V_MAX, KNOTS = -12.0, 1.0, 66
W = np.array([0.2126, 0.7152, 0.0722])
# GuidedFilter.swift
MAX_SIDE, RADIUS_FRACTION, EPSILON, LOG_FLOOR = 256, 0.057, 0.163, -14.0


def downsample(a, f=4):
    h, w = a.shape[:2]
    return a[:h // f * f, :w // f * f].reshape(h // f, f, w // f, f, -1).mean((1, 3))


def guided_base(srgb):
    """Replica of GuidedFilter.coefficientImage + base = A·log2(Y) + B."""
    h, w = srgb.shape[:2]
    lin = compare.decode(np.clip(srgb, 0, 1))
    s = MAX_SIDE / max(h, w)
    sw, sh = round(w * s), round(h * s)
    small = np.stack([np.asarray(Image.fromarray(lin[..., c].astype(np.float32), "F")
                                 .resize((sw, sh), Image.BILINEAR)) for c in range(3)], -1)
    ly = np.maximum(LOG_FLOOR, np.log2(np.maximum(small @ W, 1e-6)))
    r = max(1, round(max(sw, sh) * RADIUS_FRACTION))
    box = lambda a: uniform_filter(a, size=2 * r + 1, mode="nearest")
    m, m2 = box(ly), box(ly * ly)
    var = np.maximum(0, m2 - m * m)
    a = var / (var + EPSILON)
    b = m - a * m
    up = lambda z: np.asarray(Image.fromarray(box(z).astype(np.float32), "F").resize((w, h), Image.BILINEAR))
    own = np.maximum(np.log2(np.maximum(lin @ W, 1e-12)), LOG_FLOOR)
    return up(a) * own + up(b), own


def main():
    kit, target = Path(sys.argv[1]).expanduser(), Path(sys.argv[2]).expanduser()
    source = downsample(compare.load(kit / "source.tif"))
    base, own = guided_base(source)
    v = np.clip(ALPHA * np.clip(base, -14, 6) + (1 - ALPHA) * own, -14, 6)
    y0 = compare.decode(source) @ W
    valid = (y0 > 0.002) & (y0 < 0.98)
    grid = np.linspace(V_MIN, V_MAX, KNOTS)
    index = np.clip(np.round((v - V_MIN) / (grid[1] - grid[0])).astype(int), 0, KNOTS - 1)

    tables = {"shadows": {0.0: np.zeros(KNOTS)}, "highlights": {0.0: np.zeros(KNOTS)}}
    for key, path in compare.index(kit / "adobe").items():
        m = re.search(r"cal_\d\d_(shadows|highlights)_([mp])([\d.]+)", key)
        if not m:
            continue
        amount = (-1 if m.group(2) == "m" else 1) * float(m.group(3))
        y = compare.decode(downsample(compare.load(path))) @ W
        gain = np.log2(np.maximum(y, 1e-5) / np.maximum(y0, 1e-5))
        row = np.full(KNOTS, np.nan)
        for i in range(KNOTS):
            sel = valid & (index == i)
            if sel.sum() > 30:
                row[i] = np.median(gain[sel])
        ok = ~np.isnan(row)
        row = gaussian_filter1d(np.interp(grid, grid[ok], row[ok]), 1.0, mode="nearest")
        tables[m.group(1)][amount] = row

    fmt = lambda vals: ", ".join(f"{x:.5f}" for x in vals)
    out = [
        "// Generated by tools/calibration/fit_local.py from Lightroom exports — don't edit by hand.",
        "",
        "extension LocalTone {",
        f"    static let zoneMix = {ALPHA}  // α: weight of the local base vs. the pixel itself",
        f"    static let shadowsChroma = {BETA['shadows']}  // β",
        f"    static let highlightsChroma = {BETA['highlights']}",
        f"    static let zoneRange = ({V_MIN}, {V_MAX})  // EV, 0 = white",
        "",
        f"    /// Gain in EV at {KNOTS} zone values over `zoneRange`, per measured amount.",
        "    static let tables: [Slider: ToneModel.SliderTable] = [",
    ]
    for name in ("shadows", "highlights"):
        amounts = sorted(tables[name])
        print(f"  {name.capitalize()}: amounts {', '.join(f'{a:+g}' for a in amounts)}")
        out += [f"        .{name}: ToneModel.SliderTable(",
                f"            amounts: [{', '.join(f'{a:g}' for a in amounts)}],",
                "            offsets: ["]
        out += [f"                [{fmt(tables[name][a])}]," for a in amounts]
        out += ["            ]),"]
    out += ["    ]", "}", ""]
    target.write_text("\n".join(out))
    print(f"✓ Wrote {target}")


if __name__ == "__main__":
    main()
