#!/usr/bin/env python3
"""Fit the light sliders for RAW files (Contrast, Whites, Blacks, Shadows, Highlights).

Usage:
  python3 fit_raw_sliders.py <base.jpg> <exports folder> <output .swift file>

On RAW files Lightroom's light sliders work before the profile's tone curve (on scene
light), so they act narrower than on JPEGs (fit_tone.py / fit_local.py): Shadows and
Highlights barely touch the midtones and Contrast pivots lower. Measured on one photo:
<base.jpg> = Lightroom's default RAW export, <exports>/lr_rNN.jpg = the same photo with
preset NN (see SLIDERS). Same table formats as the JPEG fits; amounts beyond the exported
ones are extrapolated linearly to ±100. Writes RawSliderData.swift.
"""
import sys
from pathlib import Path

import numpy as np
from scipy.ndimage import gaussian_filter1d

sys.path.insert(0, str(Path(__file__).parent))
import compare  # noqa: E402
import fit_local  # noqa: E402

SLIDERS = {1: ("shadows", 50), 2: ("shadows", 100), 3: ("shadows", -50),
           4: ("highlights", -50), 5: ("highlights", -100), 6: ("highlights", 50),
           7: ("blacks", 50), 8: ("blacks", -50), 9: ("whites", 50), 10: ("whites", -50),
           11: ("contrast", 50), 12: ("contrast", -50)}
GRID = 65
W = np.array([0.2126, 0.7152, 0.0722])
enc = lambda y: np.where(y <= 0.0031308, y * 12.92, 1.055 * np.power(np.clip(y, 0, None), 1 / 2.4) - 0.055)


def tone_offsets(x_enc, y_enc):
    """Median output per input bin → offset table on GRID (0 and 1 fixed)."""
    grid = np.linspace(0, 1, GRID)
    idx = np.clip(np.round(x_enc * (GRID - 1)).astype(int), 0, GRID - 1)
    row = np.full(GRID, np.nan)
    for i in range(GRID):
        sel = idx == i
        if sel.sum() > 40:
            row[i] = np.median(y_enc[sel]) - grid[i]
    row[0], row[-1] = 0.0, row[-1] if not np.isnan(row[-1]) else 0.0
    ok = ~np.isnan(row)
    row = np.interp(grid, grid[ok], row[ok])
    row = gaussian_filter1d(row, 1.0, mode="nearest")
    row[0] = 0.0
    return row


def extend(table):
    """Add ±100 by linear extrapolation from the outermost measured amount on each side."""
    for side in (-1, 1):
        amounts = [a for a in table if a * side > 0]
        if amounts and max(abs(a) for a in amounts) < 100:
            a = max(amounts, key=abs)
            table[100.0 * side] = table[a] * (100 / abs(a))
    return table


def swift_rows(table, indent):
    fmt = lambda v: ", ".join(f"{x:.5f}" for x in v)
    return [f"{indent}[{fmt(table[a])}]," for a in sorted(table)]


def main():
    base_path, exports, target = (Path(a).expanduser() for a in sys.argv[1:4])
    base = fit_local.downsample(compare.load(base_path), 8)
    lin0 = compare.decode(base)
    y0 = lin0 @ W
    x_enc = enc(y0).ravel()
    zone_base, own = fit_local.guided_base(base)
    v = np.clip(fit_local.ALPHA * np.clip(zone_base, -14, 6) + (1 - fit_local.ALPHA) * own, -14, 6)
    knots = np.linspace(fit_local.V_MIN, fit_local.V_MAX, fit_local.KNOTS)
    zidx = np.clip(np.round((v - fit_local.V_MIN) / (knots[1] - knots[0])).astype(int), 0, fit_local.KNOTS - 1)
    valid = (y0 > 0.002) & (y0 < 0.98)

    tone = {s: {0.0: np.zeros(GRID)} for s in ("contrast", "whites", "blacks")}
    local = {s: {0.0: np.zeros(fit_local.KNOTS)} for s in ("shadows", "highlights")}
    for n, (slider, amount) in SLIDERS.items():
        out = fit_local.downsample(compare.load(exports / f"lr_r{n:02d}.jpg"), 8)
        y = compare.decode(out) @ W
        if slider in tone:
            tone[slider][float(amount)] = tone_offsets(x_enc, enc(y).ravel())
        else:
            gain = np.log2(np.maximum(y, 1e-5) / np.maximum(y0, 1e-5))
            row = np.full(fit_local.KNOTS, np.nan)
            for i in range(fit_local.KNOTS):
                sel = valid & (zidx == i)
                if sel.sum() > 30:
                    row[i] = np.median(gain[sel])
            ok = ~np.isnan(row)
            row = gaussian_filter1d(np.interp(knots, knots[ok], row[ok]), 1.0, mode="nearest")
            local[slider][float(amount)] = row
        print(f"  {slider} {amount:+d}: ok")

    lines = ["// Generated by tools/calibration/fit_raw_sliders.py from Lightroom exports — don't edit by hand.",
             "", "extension ToneModel {",
             "    /// RAW files: curve offsets like `sliderTables` (65 inputs 0…1) per amount.",
             "    static let rawSliderTables: [Slider: SliderTable] = ["]
    for s in ("contrast", "whites", "blacks"):
        t = extend(tone[s])
        lines += [f"        .{s}: SliderTable(", f"            amounts: [{', '.join(f'{a:g}' for a in sorted(t))}],",
                  "            offsets: ["] + swift_rows(t, "                ") + ["            ]),"]
    lines += ["    ]", "}", "", "extension LocalTone {",
              "    /// RAW files: gain in EV per zone value like `tables`, per amount.",
              "    static let rawTables: [Slider: ToneModel.SliderTable] = ["]
    for s in ("shadows", "highlights"):
        t = extend(local[s])
        lines += [f"        .{s}: ToneModel.SliderTable(", f"            amounts: [{', '.join(f'{a:g}' for a in sorted(t))}],",
                  "            offsets: ["] + swift_rows(t, "                ") + ["            ]),"]
    lines += ["    ]", "}", ""]
    target.write_text("\n".join(lines))
    print(f"✓ Wrote {target}")


if __name__ == "__main__":
    main()
