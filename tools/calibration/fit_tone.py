#!/usr/bin/env python3
"""Fit LumaGrader's global tone sliders (Exposure, Contrast, Whites, Blacks) to Lightroom.

Usage:
  python3 fit_tone.py <kit folder> <output .swift file>

Reads the grey ramp of <kit>/source.tif and of every Lightroom export in <kit>/adobe
(names cal_NN_<slider>_<m|p><amount>, see make_kit.py) and writes ToneModelData.swift.

Model (measured on Lightroom, Oct 2026):
  * Exposure on a rendered photo = un-render to scene light with a fixed curve H, multiply
    by 2^EV, render again:  T(x) = H(H⁻¹(x) + EV). H is fitted to all exposure files.
  * Contrast, Whites, Blacks = a tone curve offset per amount, measured at each exported
    amount and interpolated between them (more amounts exported → better in between).
  * The curves act on ProPhoto RGB (sRGB-encoded) channels, hue-preserving: the curve is
    applied to the largest and smallest channel and the middle one keeps its position.
"""
import re
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

sys.path.insert(0, str(Path(__file__).parent))
import compare  # noqa: E402

GRID = 65                          # curve samples for Contrast / Whites / Blacks
U = np.linspace(-12, 12, 49)       # scene stops for the exposure curve H
SLIDERS = ("contrast", "whites", "blacks")
W = np.array([0.2126, 0.7152, 0.0722])


def ramp(img):
    """Grey ramp as (input sRGB value, output sRGB-encoded luminance), edges skipped."""
    band = img[20:180, compare.HALF + 12:-12]
    y = compare.decode(np.clip(band, 0, 1)) @ W
    out = np.where(y <= 0.0031308, y * 12.92, 1.055 * np.power(y, 1 / 2.4) - 0.055)
    return out.mean(0)


def parse(name):
    m = re.search(r"cal_\d\d_([a-z]+)_([mp])([\d.]+)", name)
    if not m:
        return None
    return m.group(1), (-1 if m.group(2) == "m" else 1) * float(m.group(3))


def fit_exposure(x, curves):
    data = [(ev, x[::8], y[::8]) for ev, y in curves]

    # H may rise above 1 (scene light brighter than display white) so that white itself
    # darkens with −EV, as in Lightroom; outputs above 1 clip.
    def H(p):
        h = np.concatenate([[0], np.cumsum(np.exp(p[:-1]))])
        return h / h[-1] * (1 + np.exp(p[-1]))

    def T(h, xs, ev):
        return np.interp(np.interp(xs, h, U) + ev, U, h)

    def resid(p):
        h = H(p)
        return np.concatenate([np.minimum(T(h, xs, ev), 1) - ys for ev, xs, ys in data]
                              + [1e-2 * np.diff(p[:-1], 2)])

    p0 = np.append(np.log(np.diff(compare.decode(np.linspace(0, 1, U.size)) ** 0.5) + 1e-3), np.log(0.5))
    h = H(least_squares(resid, p0).x)
    for ev, xs, ys in data:
        err = np.abs(np.minimum(T(h, xs, ev), 1) - ys)
        print(f"  Exposure {ev:+g}: max error {err.max():.3f}, mean {err.mean():.4f}")
    return h


def swift_array(values, per_line=8, indent="        "):
    items = [f"{v:.8g}" for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "[\n" + ",\n".join(indent + "    " + l for l in lines) + ",\n" + indent + "]"


def main():
    kit, target = Path(sys.argv[1]).expanduser(), Path(sys.argv[2]).expanduser()
    source = compare.load(kit / "source.tif")
    x = source[20:180, compare.HALF + 12:-12, 0].mean(0)
    grid = np.linspace(0, 1, GRID)

    exposure, tables = [], {s: {0.0: np.zeros(GRID)} for s in SLIDERS}
    for key, path in compare.index(kit / "adobe").items():
        parsed = parse(key)
        if not parsed:
            continue
        slider, amount = parsed
        y = ramp(compare.load(path))
        if slider == "exposure":
            exposure.append((amount, y))
        elif slider in tables:
            curve = np.maximum.accumulate(np.interp(grid, x, y))
            tables[slider][amount] = curve - grid

    print("Fitting:")
    h = fit_exposure(x, sorted(exposure))
    out = [
        "// Generated by tools/calibration/fit_tone.py from Lightroom exports — don't edit by hand.",
        "// Re-run the script after adding exports to update these tables.",
        "",
        "extension ToneModel {",
        "    /// Scene stops for `exposureCurve` (Exposure: x → H(H⁻¹(x) + EV)).",
        f"    static let exposureStops: [Double] = {swift_array(U)}",
        "",
        "    /// H: scene stops → display value (sRGB-encoded; above 1 clips to white).",
        f"    static let exposureCurve: [Double] = {swift_array(h)}",
        "",
        f"    /// Curve offsets (output − input) at {GRID} inputs 0…1, per measured slider amount.",
        "    static let sliderTables: [Slider: SliderTable] = [",
    ]
    for slider in SLIDERS:
        amounts = sorted(tables[slider])
        print(f"  {slider.capitalize()}: amounts {', '.join(f'{a:+g}' for a in amounts)}")
        rows = ",\n".join(f"                {swift_array(tables[slider][a], indent='                ')}"
                          for a in amounts)
        out += [
            f"        .{slider}: SliderTable(",
            f"            amounts: [{', '.join(f'{a:g}' for a in amounts)}],",
            "            offsets: [",
            rows + ",",
            "            ]),",
        ]
    out += ["    ]", "}", ""]
    target.write_text("\n".join(out))
    print(f"✓ Wrote {target}")


if __name__ == "__main__":
    main()
